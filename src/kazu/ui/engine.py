"""Qt-free PaneEngine protocol decoupling Kazu from any single browser backend (Rule D5)."""

from __future__ import annotations

from typing import Any, Protocol

from kazu.controllers.lifecycle import LifecycleTier


class PaneEngine(Protocol):
    """Unified interface implemented by QtWebEngineEngine and BrowserAppEngine."""

    @property
    def widget(self) -> Any: ...

    def load_url(self, url: str) -> None: ...
    def reload(self) -> None: ...
    def back(self) -> None: ...
    def forward(self) -> None: ...
    def set_zoom(self, factor: float) -> None: ...
    def find_text(self, query: str) -> None: ...
    def set_lifecycle_tier(self, tier: LifecycleTier) -> None: ...
    def grab_snapshot_png(self) -> bytes: ...
    def focus_view(self) -> bool: ...
    def trigger_paste(self) -> None: ...
    def selected_text(self) -> str: ...
    def dispose(self) -> None: ...
